import { z } from 'zod';
import {
  CONTENT_HASH_HEX_LENGTH,
  MAX_ITEM_PAYLOAD_BYTES,
  NONCE_BYTES,
  AEAD_TAG_BYTES,
} from './constants.js';
import { base64ToBytes, bytesToBase64 } from './encoding.js';
import { ProtocolError } from './errors.js';
import { ULID_REGEX } from './ulid.js';

/** Opaque identifier for spaces and devices (assigned by the relay). */
export const IdSchema = z
  .string()
  .min(1)
  .max(128)
  .regex(/^[A-Za-z0-9_-]+$/, 'must be [A-Za-z0-9_-]');

export const UlidSchema = z.string().regex(ULID_REGEX, 'must be a canonical ULID');

/** Item kind, e.g. `clipboard.text`. Lowercase dotted segments. */
export const KindSchema = z
  .string()
  .max(64)
  .regex(/^[a-z][a-z0-9-]*(\.[a-z][a-z0-9-]*)+$/, 'must be dotted lowercase, e.g. clipboard.text');

export const SchemaVersionSchema = z.number().int().min(1).max(0xffff_ffff);

/** Unix epoch milliseconds (non-negative safe integer). */
export const TimestampMsSchema = z.number().int().min(0).max(Number.MAX_SAFE_INTEGER);

export const ContentHashSchema = z
  .string()
  .length(CONTENT_HASH_HEX_LENGTH)
  .regex(/^[0-9a-f]+$/, 'must be lowercase hex');

/**
 * Metadata that is authenticated (but not encrypted) with every item. The
 * relay can read these fields; they are bound to the ciphertext as AEAD
 * associated data so they cannot be altered without detection.
 */
export interface SyncItemMeta {
  /** ULID, generated by the origin device. */
  id: string;
  spaceId: string;
  originDeviceId: string;
  /** Kind plugin identifier, e.g. `clipboard.text`. */
  kind: string;
  /** Version of the kind's plaintext serialization. */
  schemaVersion: number;
  /** Creation time on the origin device, Unix epoch ms. */
  createdAt: number;
}

/** An encrypted item as held in memory by clients and the relay. */
export interface SyncItem extends SyncItemMeta {
  /** AES-256-GCM ciphertext including the 16-byte tag. */
  payload: Uint8Array;
  /** 96-bit AES-GCM nonce, fresh and random per item. */
  nonce: Uint8Array;
  /** Keyed content hash (HMAC-SHA-256, lowercase hex); see @syncert/crypto. */
  contentHash: string;
}

const base64Field = (label: string, minBytes: number, maxBytes: number) =>
  z
    .string()
    // Cheap upper bound before decoding.
    .max(Math.ceil(maxBytes / 3) * 4)
    .superRefine((value, ctx) => {
      let bytes: Uint8Array;
      try {
        bytes = base64ToBytes(value);
      } catch {
        ctx.addIssue({ code: 'custom', message: `${label} must be canonical base64` });
        return;
      }
      if (bytes.length < minBytes || bytes.length > maxBytes) {
        ctx.addIssue({
          code: 'custom',
          message: `${label} must be ${minBytes}..${maxBytes} bytes, got ${bytes.length}`,
        });
      }
    });

/** JSON wire form of a {@link SyncItem}: binary fields are standard base64. */
export const WireSyncItemSchema = z.strictObject({
  id: UlidSchema,
  spaceId: IdSchema,
  originDeviceId: IdSchema,
  kind: KindSchema,
  schemaVersion: SchemaVersionSchema,
  createdAt: TimestampMsSchema,
  payload: base64Field('payload', AEAD_TAG_BYTES, MAX_ITEM_PAYLOAD_BYTES),
  nonce: base64Field('nonce', NONCE_BYTES, NONCE_BYTES),
  contentHash: ContentHashSchema,
});

export type WireSyncItem = z.infer<typeof WireSyncItemSchema>;

/** Convert an in-memory item to its JSON wire form (validates the result). */
export function itemToWire(item: SyncItem): WireSyncItem {
  const wire: WireSyncItem = {
    id: item.id,
    spaceId: item.spaceId,
    originDeviceId: item.originDeviceId,
    kind: item.kind,
    schemaVersion: item.schemaVersion,
    createdAt: item.createdAt,
    payload: bytesToBase64(item.payload),
    nonce: bytesToBase64(item.nonce),
    contentHash: item.contentHash,
  };
  const parsed = WireSyncItemSchema.safeParse(wire);
  if (!parsed.success) {
    throw new ProtocolError('invalid sync item', formatIssues(parsed.error));
  }
  return wire;
}

/** Convert (and validate) a wire item into an in-memory item. */
export function itemFromWire(input: unknown): SyncItem {
  const parsed = WireSyncItemSchema.safeParse(input);
  if (!parsed.success) {
    throw new ProtocolError('invalid wire sync item', formatIssues(parsed.error));
  }
  const w = parsed.data;
  return {
    id: w.id,
    spaceId: w.spaceId,
    originDeviceId: w.originDeviceId,
    kind: w.kind,
    schemaVersion: w.schemaVersion,
    createdAt: w.createdAt,
    payload: base64ToBytes(w.payload),
    nonce: base64ToBytes(w.nonce),
    contentHash: w.contentHash,
  };
}

/** @internal */
export function formatIssues(error: z.ZodError): string[] {
  return error.issues.map((i) => `${i.path.join('.') || '<root>'}: ${i.message}`);
}
